package config_test

import (
	"strings"
	"testing"

	"github.com/buildfoundry-nz/formwork/internal/config"
)

const genRules = "rules:\n" +
	"  - id: no-widget\n    type: forbidden-pattern\n    scope: {include: ['**/*.go']}\n    params: {pattern: WIDGET}\n" +
	"  - id: codegen-fresh\n    type: forbidden-pattern\n    scope: {include: ['**/*.go'], generated: true}\n    params: {pattern: NEVER}\n"

func genRepo(t *testing.T, generated string) string {
	t.Helper()
	return writeRepo(t, map[string]string{
		".formwork/formwork.yaml":   "version: 1\n" + generated,
		".formwork/rules/main.yaml": genRules,
	})
}

func TestGeneratedDefinitionIsSharedByEveryRule(t *testing.T) {
	cfg, err := config.Load(genRepo(t, "generated:\n  - {marker: 'Code generated by protoc-gen-go. DO NOT EDIT.', proven_by: [codegen-fresh]}\n"))
	if err != nil {
		t.Fatal(err)
	}
	if cfg.Generation == nil || len(cfg.Generation.Markers) != 1 {
		t.Fatalf("Generation = %+v, want the one marker", cfg.Generation)
	}
	for _, r := range cfg.Rules {
		if r.Generation() != cfg.Generation {
			t.Fatalf("rule %s does not carry the config's generation", r.ID)
		}
	}
	if cfg.Rules[0].JudgesGenerated() == cfg.Rules[1].JudgesGenerated() {
		t.Fatal("scope.generated: true must set JudgesGenerated on that rule alone")
	}
}

// The header, and only the header: the marker in a string, or in a comment
// after code, declares nothing.
func TestDeclaresReadsOnlyTheLeadingCommentBlock(t *testing.T) {
	cfg, err := config.Load(genRepo(t, "generated:\n  - {marker: 'DO NOT EDIT.', proven_by: [codegen-fresh]}\n"))
	if err != nil {
		t.Fatal(err)
	}
	g := cfg.Generation
	for _, tc := range []struct {
		name, src string
		want      bool
	}{
		{"go generator header", "// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage p\n", true},
		{"header after a build tag and blank lines", "//go:build linux\n\n// Code generated x. DO NOT EDIT.\npackage p\n", true},
		{"marker in a string", "package p\n\nconst s = \"DO NOT EDIT.\"\n", false},
		{"marker in a comment after code", "package p\n\n// DO NOT EDIT.\n", false},
	} {
		if _, got := g.Declares([]byte(tc.src)); got != tc.want {
			t.Errorf("%s: Declares = %v, want %v", tc.name, got, tc.want)
		}
	}
}

func TestLoadRejectsBadGeneratedDefinition(t *testing.T) {
	for _, tc := range []struct{ name, gen, want string }{
		{"no proving rule", "generated:\n  - {marker: 'DO NOT EDIT.'}\n", "proven_by is required"},
		{"proving rule not in the corpus", "generated:\n  - {marker: 'DO NOT EDIT.', proven_by: [nope]}\n", "names no rule"},
		{"empty marker", "generated:\n  - {marker: '', proven_by: [codegen-fresh]}\n", "marker is empty"},
		{"duplicate marker", "generated:\n  - {marker: 'X', proven_by: [codegen-fresh]}\n  - {marker: 'X', proven_by: [codegen-fresh]}\n", "declared twice"},
		{"unknown key", "generated:\n  - {marker: 'X', proven_by: [codegen-fresh], why: y}\n", "why"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			_, err := config.Load(genRepo(t, tc.gen))
			if err == nil || !strings.Contains(err.Error(), tc.want) {
				t.Fatalf("Load error = %v, want it to mention %q", err, tc.want)
			}
		})
	}
}
