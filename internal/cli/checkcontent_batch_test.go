func runBatch(t *testing.T, input string, args ...string) (int, []contentDocument, string) {
	t.Helper()
	code, out, errOut := invokeContent(t, input, args...)
	if out == "" {
		return code, nil, errOut
	}
	if !strings.HasSuffix(out, "\n") {
		t.Fatalf("batch output does not end each result with a newline: %q", out)
	}
	lines := strings.Split(strings.TrimSuffix(out, "\n"), "\n")
	docs := make([]contentDocument, 0, len(lines))
	for i, line := range lines {
		if line == "" {
			t.Fatalf("batch output contains an empty result line at %d", i+1)
		}
		docs = append(docs, decodeContent(t, line))
	}
	return code, docs, errOut
}

func TestCheckContentBatchPreservesOrderFindingsAndReplayIdentity(t *testing.T) {
	root := contentRepo(t, "", `rules:
  - id: no-todo
    type: forbidden-pattern
    scope: {include: ['**']}
    params: {pattern: TODO}
`)
	input := "{\"path\":\"b.txt\",\"content\":\"TODO b\\n\"}\n" +
		"{\"path\":\"a.txt\",\"content\":\"clean a\\n\"}\n"
	code, docs, errOut := runBatch(t, input, "check-content", "-C", root, "--batch")
	if code != 1 || len(docs) != 2 {
		t.Fatalf("batch clean+violation: code=%d docs=%+v stderr=%s", code, docs, errOut)
	}
	if docs[0].Path != "b.txt" || docs[0].Status != "findings" || docs[1].Path != "a.txt" || docs[1].Status != "clean" {
		t.Fatalf("batch did not preserve input order/status: %+v", docs)
	}
	if docs[0].FindingsTotal != 1 || docs[0].Findings[0].Path != "b.txt" || docs[1].FindingsTotal != 0 {
		t.Fatalf("batch findings leaked between files: %+v", docs)
	}
	if docs[0].ContentHash == docs[1].ContentHash || docs[0].ReplayHandle == docs[1].ReplayHandle {
		t.Fatal("independent records share content/replay identity")
	}
	if docs[0].CorpusHash != docs[1].CorpusHash {
		t.Fatal("one invocation produced different corpus hashes")
	}
}

func TestCheckContentBatchNoEligibleCleanAndFinalizerIsolation(t *testing.T) {
	root := contentRepo(t, "", `rules:
  - id: local
    type: forbidden-pattern
    scope: {include: ['in/**']}
    params: {pattern: TODO}
  - id: tree
    type: required-pattern
    scope: {include: ['in/**']}
    params: {pattern: REQUIRED, mode: exists}
`)
	input := "{\"path\":\"out/a.txt\",\"content\":\"clean\\n\"}\n" +
		"{\"path\":\"in/a.txt\",\"content\":\"clean\\n\"}\n"
	code, docs, errOut := runBatch(t, input, "check-content", "-C", root, "--batch")
	if code != 0 || len(docs) != 2 {
		t.Fatalf("batch no_eligible/clean: code=%d docs=%+v stderr=%s", code, docs, errOut)
	}
	if docs[0].Status != "no_eligible_rules" || docs[1].Status != "clean" {
		t.Fatalf("clean and zero-eligible states were conflated: %+v", docs)
	}
	if got := notEvaluatedReasons(docs[1])["tree"]; got != "finalizer" {
		t.Fatalf("finalizer reason = %q, want finalizer", got)
	}
	if len(docs[1].EvaluatedRuleIDs) != 1 || docs[1].EvaluatedRuleIDs[0] != "local" {
		t.Fatalf("a finalizer/cross-file rule ran: %+v", docs[1])
	}
}

func TestCheckContentBatchGeneratedStateIsPerRecord(t *testing.T) {
	root := contentRepo(t, "version: 1\ngenerated:\n  - marker: 'Code generated by test'\n    proven_by: [generated-only]\n", `rules:
  - id: ordinary
    type: forbidden-pattern
    scope: {include: ['**']}
    params: {pattern: TODO}
  - id: generated-only
    type: forbidden-pattern
    scope: {include: ['**'], generated: true}
    params: {pattern: TODO}
`)
	input := "{\"path\":\"ordinary.go\",\"content\":\"clean\\n\"}\n" +
		"{\"path\":\"generated.go\",\"content\":\"// Code generated by test. DO NOT EDIT.\\nclean\\n\"}\n"
	code, docs, errOut := runBatch(t, input, "check-content", "-C", root, "--batch")
	if code != 0 || len(docs) != 2 {
		t.Fatalf("batch generated state: code=%d docs=%+v stderr=%s", code, docs, errOut)
	}
	if docs[0].Status != "clean" || docs[1].Status != "no_eligible_rules" {
		t.Fatalf("generated state leaked across records: %+v", docs)
	}
	if got := notEvaluatedReasons(docs[1])["ordinary"]; got != "generated_excluded" {
		t.Fatalf("generated record ordinary reason = %q, want generated_excluded", got)
	}
}

func TestCheckContentBatchNotScannedDoesNotInvalidateOtherRecords(t *testing.T) {
	root := contentRepo(t, "version: 1\nscan:\n  ignore:\n    - glob: 'ignored/**'\n      reason: foreign tree\n", `rules:
  - id: no-todo
    type: forbidden-pattern
    scope: {include: ['**']}
    params: {pattern: TODO}
`)
	input := "{\"path\":\"ignored/a.txt\",\"content\":\"TODO\\n\"}\n" +
		"{\"path\":\"visible.txt\",\"content\":\"clean\\n\"}\n"
	code, docs, errOut := runBatch(t, input, "check-content", "-C", root, "--batch")
	if code != 0 || len(docs) != 2 {
		t.Fatalf("batch not_scanned: code=%d docs=%+v stderr=%s", code, docs, errOut)
	}
	if docs[0].Status != "not_scanned" || docs[0].NotScanned == nil || docs[0].NotScanned.By != "scan.ignore" {
		t.Fatalf("first record lost not_scanned attribution: %+v", docs[0])
	}
	if docs[1].Status != "clean" || docs[1].Coverage.Evaluated != 1 {
		t.Fatalf("not_scanned invalidated visible record: %+v", docs[1])
	}
}

func TestCheckContentBatchRejectsEmptyAndMalformedInput(t *testing.T) {
	root := contentRepo(t, "", "rules: []\n")
	for _, input := range []string{
		"",
		"\n",
		"not-json\n",
		"{\"path\":\"a.txt\",\"content\":\"\",\"extra\":true}\n",
		"{\"path\":\"a.txt\"}\n",
		"{\"path\":\"a.txt\",\"content\":null}\n",
		"{\"content\":\"\"}\n",
		"{\"path\":\"a.txt\",\"content\":\"\"} {\"path\":\"b.txt\",\"content\":\"\"}\n",
		"{\"path\":\"a.txt\",\"content\":\"\"}\nnot-json\n",
	} {
		code, out, errOut := invokeContent(t, input, "check-content", "-C", root, "--batch")
		if code != 2 || out != "" || errOut == "" {
			t.Errorf("input %q: code=%d out=%q stderr=%q, want fail-closed exit 2", input, code, out, errOut)
		}
	}
}

func TestCheckContentBatchAllFindingsIsPerRecord(t *testing.T) {
	root := contentRepo(t, "", `rules:
  - id: no-todo
    type: forbidden-pattern
    scope: {include: ['**']}
    params: {pattern: TODO}
`)
	input := "{\"path\":\"a.txt\",\"content\":\"TODO 1\\nTODO 2\\nTODO 3\\nTODO 4\\n\"}\n"
	code, bounded, errOut := runBatch(t, input, "check-content", "-C", root, "--batch")
	if code != 1 || len(bounded) != 1 || len(bounded[0].Findings) != 3 || bounded[0].FindingsTotal != 4 || bounded[0].FindingsOmitted != 1 {
		t.Fatalf("bounded batch record: code=%d docs=%+v stderr=%s", code, bounded, errOut)
	}
	code, all, errOut := runBatch(t, input, "check-content", "-C", root, "--batch", "--all-findings")
	if code != 1 || len(all) != 1 || len(all[0].Findings) != 4 || all[0].FindingsOmitted != 0 {
		t.Fatalf("all-findings batch record: code=%d docs=%+v stderr=%s", code, all, errOut)
	}
	if all[0].ReplayHandle != bounded[0].ReplayHandle {
		t.Fatal("output bound changed batch replay identity")
	}
}

func TestCheckContentBatchEngineAndReadErrorsEmitNoPartialResults(t *testing.T) {
	t.Run("engine error", func(t *testing.T) {
		root := contentRepo(t, "", `rules:
  - id: go-budget
    type: go/func-line-budget
    scope: {include: ['**/*.go']}
    params: {max_lines: 1}
`)
		input := "{\"path\":\"good.go\",\"content\":\"package p\\n\"}\n" +
			"{\"path\":\"bad.go\",\"content\":\"package p\\nfunc (\\n\"}\n"
		code, out, errOut := invokeContent(t, input, "check-content", "-C", root, "--batch")
		if code != 2 || out != "" || !strings.Contains(errOut, "go-budget") {
			t.Fatalf("batch engine error: code=%d out=%q stderr=%q", code, out, errOut)
		}
	})
	t.Run("stdin error", func(t *testing.T) {
		root := contentRepo(t, "", "rules: []\n")
		var stdout, stderr bytes.Buffer
		code := cli.Run([]string{"check-content", "-C", root, "--batch"}, failingContentReader{}, &stdout, &stderr)
		if code != 2 || stdout.Len() != 0 || !strings.Contains(stderr.String(), "stdin exploded") {
			t.Fatalf("batch stdin error: code=%d stdout=%q stderr=%q", code, stdout.String(), stderr.String())
		}
	})
}

func TestCheckContentBatchRejectsPathAndEmitsWriteErrors(t *testing.T) {
	root := contentRepo(t, "", "rules: []\n")
	code, out, _ := invokeContent(t, "", "check-content", "-C", root, "--batch", "--path", "a.txt")
	if code != 2 || out != "" {
		t.Fatalf("--batch with --path: code=%d out=%q, want exit 2", code, out)
	}

	var stderr bytes.Buffer
	input := "{\"path\":\"a.txt\",\"content\":\"\"}\n{\"path\":\"b.txt\",\"content\":\"\"}\n"
	code = cli.Run([]string{"check-content", "-C", root, "--batch"}, strings.NewReader(input), failingContentWriter{}, &stderr)
	if code != 2 || !strings.Contains(stderr.String(), "writing json") || !strings.Contains(stderr.String(), "stdout ENOSPC") {
		t.Fatalf("batch stdout error: code=%d stderr=%q, want exit 2", code, stderr.String())
	}
}
