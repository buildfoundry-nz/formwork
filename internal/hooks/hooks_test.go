func TestInstallIsIdempotent(t *testing.T) {
	dir := repo(t)
	cfg := &config.Config{Lanes: []config.Lane{{Name: "pre-commit", All: true}}, Rules: []*config.Rule{{ID: "r"}}, RuleFiles: 1}
	if _, err := hooks.Install(dir, cfg, false); err != nil {
		t.Fatal(err)
	}
	if _, err := hooks.Install(dir, cfg, false); err != nil {
		t.Fatalf("second install should succeed: %v", err)
	}
	if p, err := hooks.Verify(dir, cfg); err != nil || len(p) != 0 {
		t.Fatalf("verify after re-install: %v (err=%v)", p, err)
	}
}

func readShim(t *testing.T, dir, name string) string {
	t.Helper()
	b, err := os.ReadFile(filepath.Join(dir, ".formwork", "hooks", name))
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}

// A git-hook lane that selects no rules is a wiring defect, not a healthy
// install. The shim runs `formwork check --lane <name>`, which refuses an empty
// lane (exit 2, #151 row 10) — so installing one produces a hook that aborts
// EVERY commit, with nothing in the hook's output the developer can act on.
//
// Before this guard, install printed "installed git hooks: pre-commit" and
// verify printed "hooks wired", both exit 0, while no commit could be made. The
// two commands whose entire job is certifying the wiring — one of which replaces
// the shell system's hooks-wired CI gate — both certified it.
func TestInstallRefusesAGitHookLaneThatSelectsNoRules(t *testing.T) {
	dir := repo(t)
	cfg := &config.Config{
		Lanes:     []config.Lane{{Name: "pre-commit", Tags: []string{"sql"}}},
		Rules:     []*config.Rule{{ID: "r", Tags: []string{"go"}}}, // no sql-tagged rule
		RuleFiles: 1,
	}
	_, err := hooks.Install(dir, cfg, false)
	if err == nil {
		t.Fatal("installed a hook that would abort every commit")
	}
	if !strings.Contains(err.Error(), "pre-commit") {
		t.Errorf("the error must name the lane: %v", err)
	}

	// Verify must agree. A hook wired by an older binary is still installed on
	// disk, so verify has to report the condition independently of install.
	problems, err := hooks.Verify(dir, cfg)
	if err != nil {
		t.Fatal(err)
	}
	if len(problems) == 0 {
		t.Fatal("verify reported the wiring healthy")
	}
	found := false
	for _, p := range problems {
		if strings.Contains(p, "selects no rules") {
			found = true
		}
	}
	if !found {
		t.Errorf("verify did not name the empty lane: %v", problems)
	}
}
